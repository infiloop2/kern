#!/usr/bin/env python3
"""Operator-only bootstrap, copied from the integration guide into macOS Terminal.

Creates four role secrets and database grants. Never run by an agent with the
integration key: that key intentionally cannot create secrets or use the master.
"""
from __future__ import annotations

import argparse
import json
import re
import secrets
import subprocess
import sys
import tempfile

if sys.version_info < (3, 10):
    raise SystemExit("Use Python 3.10 or newer to run the Aurora setup script.")

def identifier(value: str) -> str:
    if not re.fullmatch(r"[a-z][a-z0-9_]{0,62}", value):
        raise ValueError("Names must be 1-63 lowercase letters, digits or underscores, starting with a letter.")
    return value


ROLES = ("kern_reader", "kern_writer", "kern_ddl", "kern_dropper")


def bootstrap_statements(database: str, schema: str, passwords: dict[str, str]) -> list[str]:
    identifier(database)
    identifier(schema)
    # Passwords are generated by the standalone setup script. Quotes are still
    # escaped so this function never turns a password into executable SQL.
    statements = ["SET password_encryption = 'scram-sha-256'"]
    for role in ROLES:
        password = passwords[role].replace("'", "''")
        statements.append(f"CREATE ROLE {role} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION PASSWORD '{password}'")
        statements.extend((f"ALTER ROLE {role} SET statement_timeout = '20s'",
                           f"ALTER ROLE {role} SET lock_timeout = '5s'",
                           f"ALTER ROLE {role} SET idle_in_transaction_session_timeout = '60s'"))
    statements.extend([
        # Aurora masters have CREATEROLE, not PostgreSQL SUPERUSER. Membership
        # is needed for schema ownership and another role's default grants.
        "EXECUTE format('GRANT kern_ddl TO %I', session_user)",
        f'REVOKE ALL ON DATABASE "{database}" FROM PUBLIC',
        f'GRANT CONNECT ON DATABASE "{database}" TO ' + ', '.join(ROLES),
        'REVOKE CREATE ON SCHEMA public FROM PUBLIC',
        f'CREATE SCHEMA "{schema}" AUTHORIZATION kern_ddl',
        f'GRANT USAGE ON SCHEMA "{schema}" TO kern_reader, kern_writer',
        f'ALTER DEFAULT PRIVILEGES FOR ROLE kern_ddl IN SCHEMA "{schema}" GRANT SELECT ON TABLES TO kern_reader, kern_writer',
        f'ALTER DEFAULT PRIVILEGES FOR ROLE kern_ddl IN SCHEMA "{schema}" GRANT INSERT ON TABLES TO kern_writer',
        'ALTER DEFAULT PRIVILEGES FOR ROLE kern_ddl REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC',
        'ALTER ROLE kern_reader SET default_transaction_read_only = on',
        # Membership is one-way. DDL sessions cannot SET ROLE to dropper.
        'GRANT kern_ddl TO kern_dropper',
        'CREATE SCHEMA kern_control',
        'REVOKE ALL ON SCHEMA kern_control FROM PUBLIC',
        """CREATE FUNCTION kern_control.block_unapproved_drop() RETURNS event_trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  IF session_user IN ('kern_reader', 'kern_writer', 'kern_ddl') THEN
    RAISE EXCEPTION 'Use the approved drop_table action';
  END IF;
END;
$$""",
        'REVOKE ALL ON FUNCTION kern_control.block_unapproved_drop() FROM PUBLIC',
        'CREATE EVENT TRIGGER kern_block_unapproved_drop ON sql_drop EXECUTE FUNCTION kern_control.block_unapproved_drop()',
        "EXECUTE format('REVOKE kern_ddl FROM %I', session_user)",
    ])
    return statements


def aws(region: str, service: str, operation: str, payload: dict) -> dict:
    # Credentials and passwords never appear on argv or in printed subprocess
    # stderr. Temporary request files are 0600 and removed even on failure.
    with tempfile.NamedTemporaryFile(mode="w+", encoding="utf-8", prefix="kern-aurora-", suffix=".json") as request:
        json.dump(payload, request)
        request.flush()
        result = subprocess.run(["aws", "--region", region, service, operation,
            "--cli-input-json", "file://" + request.name, "--output", "json", "--no-cli-pager"],
            capture_output=True, text=True, timeout=60, check=False)
    if result.returncode:
        raise RuntimeError(f"AWS {service} {operation} failed. Inspect IAM, Data API and database setup in AWS; provider stderr is withheld because it may contain credentials.")
    return json.loads(result.stdout)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--region", required=True)
    parser.add_argument("--cluster-arn", required=True)
    parser.add_argument("--master-secret-arn", required=True)
    parser.add_argument("--database", default="agent_store")
    parser.add_argument("--schema", default="agent_data")
    args = parser.parse_args()
    identifier(args.database)
    identifier(args.schema)
    if args.schema in {"public", "information_schema"} or args.schema.startswith("pg_"):
        raise ValueError("Use a dedicated schema, not public, information_schema or a pg_ name.")
    if not re.fullmatch(r"(?:af|ap|ca|eu|il|me|mx|sa|us)-[a-z]+-[0-9]", args.region):
        raise ValueError("Use an AWS commercial region with Data API support.")
    cluster = re.fullmatch(r"arn:aws:rds:" + re.escape(args.region) + r":([0-9]{12}):cluster:([a-zA-Z0-9-]{1,63})", args.cluster_arn)
    if not cluster:
        raise ValueError("Cluster ARN must match the selected AWS region.")
    if not re.fullmatch(r"arn:aws:secretsmanager:" + re.escape(args.region) + ":" + cluster[1] + r":secret:[a-zA-Z0-9/_+=.@!-]{1,512}", args.master_secret_arn):
        raise ValueError("Master secret ARN must match the cluster account and region.")
    passwords = {role: secrets.token_urlsafe(32) for role in ROLES}
    arns = {}
    print("Creating four role secrets. Use a fresh dedicated database; existing roles are never changed.", flush=True)
    for role in ROLES:
        response = aws(args.region, "secretsmanager", "create-secret", {
            "Name": f"kern/{cluster[2]}/{args.database}/{role}",
            "SecretString": json.dumps({"username":role, "password":passwords[role]}),
        })
        arns[role] = response["ARN"]
        print(f"Created secret for {role}.", flush=True)
    sql = "DO $kern_setup$\nBEGIN\n" + ";\n".join(bootstrap_statements(args.database, args.schema, passwords)) + ";\nEND;\n$kern_setup$;"
    print("Applying roles, grants and drop protection atomically through the master Data API connection.", flush=True)
    aws(args.region, "rds-data", "execute-statement", {"resourceArn":args.cluster_arn,
        "secretArn":args.master_secret_arn, "database":args.database, "sql":sql})
    print("Bootstrap complete. Save these values in Home > Integrations along with a separately scoped IAM access key:")
    output = {"AWS_REGION":args.region, "CLUSTER_ARN":args.cluster_arn, "DATABASE":args.database, "SCHEMA":args.schema}
    output.update({role.removeprefix("kern_").upper() + "_SECRET_ARN":arn for role, arn in arns.items()})
    print(json.dumps({"AURORA_POSTGRES_"+key:value for key,value in output.items()}, indent=2))


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, ValueError, KeyError, OSError, subprocess.TimeoutExpired):
        print("Setup did not complete. Do not blindly rerun: secrets may exist and a timed-out database call may have committed. Inspect the kern/<cluster>/<database>/ role secrets and database roles in AWS. Repair or remove only this setup's unused resources before trying again. Passwords were not printed.", file=sys.stderr)
        sys.exit(1)
